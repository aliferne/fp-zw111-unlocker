#!/usr/bin/env bash
set -euo pipefail

PORT="${1:-/dev/ttyACM1}"

stty -F "$PORT" 57600 cs8 -parenb -cstopb -ixon -ixoff raw

send() {
  printf "$1" > "$PORT"
}

